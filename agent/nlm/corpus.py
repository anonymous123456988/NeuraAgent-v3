def _expanded() -> str:
    """程序化扩充语料：对话模板 × 变量替换 + 知识句（数据增强）。"""
    parts = []
    # 1) 基础问答
    for q, a in _QA_TEMPLATES:
        parts.append(f"用户说：{q}。NEURA 回答：{a}。\n")
    # 2) 城市变体
    for city in _CITIES:
        for q_tpl, a_tpl in _CITY_QA:
            parts.append(f"用户说：{q_tpl.format(city)}。NEURA 回答：{a_tpl.format(city)}。\n")
    # 3) 文件变体
    for f in _FILES:
        for q_tpl, a_tpl in _FILE_QA:
            parts.append(f"用户说：{q_tpl.format(f)}。NEURA 回答：{a_tpl.format(f)}。\n")
    # 4) 程序变体
    for prg in _PROGRAMS:
        for q_tpl, a_tpl in _CODE_QA:
            parts.append(f"用户说：{q_tpl.format(prg)}。NEURA 回答：{a_tpl.format(prg)}。\n")
    # 5) 搜索变体
    for topic in _TOPICS:
        for q_tpl, a_tpl in _SEARCH_QA:
            parts.append(f"用户说：{q_tpl.format(topic)}。NEURA 回答：{a_tpl.format(topic)}。\n")
    # 6) 知识句(正序 + 轻微变体句式)
    parts.extend(f"{s}\n" for s in _KNOW_SENT)
    for s in _KNOW_SENT:
        parts.append(f"知识要点：{s}\n")
    return "".join(parts)


